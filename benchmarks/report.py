"""Turn benchmarks/results/*.json into markdown tables + PNG charts.

    python3 benchmarks/report.py     -> benchmarks/results/summary.md, benchmarks/charts/*.png

Every number in docs/engineering-case-study/04-benchmark-results.md is copied from
the summary.md this script writes; nothing is typed in by hand.
"""

from __future__ import annotations

import json
import statistics as st
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parent
RES, CH = HERE / "results", HERE / "charts"
CH.mkdir(exist_ok=True)
# Reference categorical slots 1-3 (validated all-pairs for <=3 series), recessive ink for axes.
C = {"baseline": "#2a78d6", "after": "#eb6834", "after-limit40": "#1baf7a"}
INK, MUTED, GRID = "#0b0b0b", "#52514e", "#e4e3df"
LABEL = {"baseline": "baseline (repo HEAD c76a78a)", "after": "after (limiter=8, default)",
         "after-limit40": "after (limiter=40)"}


def load(name):
    p = RES / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else {}


def style(ax, title, xlabel, ylabel):
    ax.set_title(title, loc="left", fontsize=12, color=INK, pad=12)
    ax.set_xlabel(xlabel, color=MUTED); ax.set_ylabel(ylabel, color=MUTED)
    ax.grid(axis="y", color=GRID, linewidth=0.8); ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(GRID)
    ax.tick_params(colors=MUTED)


def s1_table(d):
    rows = [r for r in d.get("S1", []) if "endpoint" in r]
    out = {}
    for r in rows:
        out.setdefault((r["endpoint"], r["concurrency"]), []).append(r)
    agg = {}
    for k, rs in out.items():
        agg[k] = {m: round(st.median(x[m] for x in rs), 2) for m in ("rps", "p50", "p95", "p99")}
        agg[k]["trials"] = len(rs)
        agg[k]["errors"] = sum(v for x in rs for s, v in x["statuses"].items() if not s.startswith(("2", "4")))
    return agg


def main():
    b, a, a40 = load("baseline"), load("after"), load("after-limit40")
    md = ["# Benchmark summary (generated by benchmarks/report.py)\n"]
    for name, d in (("baseline", b), ("after", a)):
        if d.get("env"):
            md.append(f"- **{name} env**: `{json.dumps(d['env'], ensure_ascii=False)}`")
    md.append("")

    # ---- S1
    sb, sa = s1_table(b), s1_table(a)
    if sb:
        md += ["## S1 — API latency / throughput (median of trials; ms)\n",
               "| endpoint | conc | base rps | base p50 | base p95 | base p99 | after rps | after p50 | after p95 | after p99 |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        for k in sorted(sb, key=lambda k: (list(dict.fromkeys(e for e, _ in sb)).index(k[0]), k[1])):
            x, y = sb[k], sa.get(k, {})
            md.append(f"| {k[0]} | {k[1]} | {x['rps']} | {x['p50']} | {x['p95']} | {x['p99']} | "
                      f"{y.get('rps', '–')} | {y.get('p50', '–')} | {y.get('p95', '–')} | {y.get('p99', '–')} |")
        md.append("")
        # chart: p50 & p99 at concurrency 8 per endpoint
        eps = list(dict.fromkeys(e for e, _ in sb))
        fig, ax = plt.subplots(figsize=(9, 4.6), dpi=150)
        w = 0.38
        for i, (lab, src) in enumerate((("baseline", sb), ("after", sa))):
            if not src:
                continue
            xs = [j + (i - 0.5) * w for j in range(len(eps))]
            p50 = [src.get((e, 8), {}).get("p50", 0) for e in eps]
            p99 = [src.get((e, 8), {}).get("p99", 0) for e in eps]
            ax.bar(xs, p99, w * 0.92, color=C[lab], alpha=0.35, label=f"{LABEL[lab]} p99")
            ax.bar(xs, p50, w * 0.92, color=C[lab], label=f"{LABEL[lab]} p50")
        ax.set_xticks(range(len(eps)))
        ax.set_xticklabels([e.replace("POST /api/generate ", "generate\n").replace("GET ", "") for e in eps], fontsize=8)
        style(ax, "S1 · latency at concurrency 8 (p50 solid, p99 light)", "", "ms")
        ax.legend(frameon=False, fontsize=8)
        fig.tight_layout(); fig.savefig(CH / "s1-latency-c8.png"); plt.close(fig)

    # ---- S2
    def s2(d):
        g = {}
        for r in d.get("S2", []):
            g.setdefault((r["upload"], r["inflight"]), []).append(r)
        return {k: {"health_ms": round(st.median(x["health_ms"] for x in v), 1),
                    "gen_wall_ms": (round(st.median(x["generate_wall_ms"] for x in v), 0) if v[0]["generate_wall_ms"] else None),
                    "trials": len(v)} for k, v in g.items()}
    s2b, s2a, s2a40 = s2(b), s2(a), s2(a40)
    if s2b:
        md += ["## S2 — /api/health latency while N simulated 5 s generations are in flight (median of 3 trials)\n",
               "| upload | in-flight | base health ms | base gen wall ms | after(8) health ms | after(8) gen wall ms | after(40) health ms | after(40) gen wall ms |",
               "|---|---|---|---|---|---|---|---|"]
        for k in sorted(s2b):
            f = lambda src, m: src.get(k, {}).get(m, "–")  # noqa: E731
            md.append(f"| {k[0]} | {k[1]} | {f(s2b,'health_ms')} | {f(s2b,'gen_wall_ms')} | {f(s2a,'health_ms')} | {f(s2a,'gen_wall_ms')} | {f(s2a40,'health_ms')} | {f(s2a40,'gen_wall_ms')} |")
        md.append("")
        fig, axes = plt.subplots(1, 2, figsize=(10, 4.2), dpi=150)
        for lab, src in (("baseline", s2b), ("after", s2a), ("after-limit40", s2a40)):
            if not src:
                continue
            ks = sorted(k for k in src if k[0] == "tiny-1x1.png")
            axes[0].plot([k[1] for k in ks], [src[k]["health_ms"] for k in ks], marker="o", ms=5, lw=2, color=C[lab], label=LABEL[lab])
            ks2 = [k for k in ks if src[k]["gen_wall_ms"]]
            axes[1].plot([k[1] for k in ks2], [src[k]["gen_wall_ms"] / 1000 for k in ks2], marker="o", ms=5, lw=2, color=C[lab], label=LABEL[lab])
        style(axes[0], "S2 · /api/health latency", "generations in flight (simulated 5 s provider)", "ms")
        style(axes[1], "S2 · time to finish all N generations", "generations in flight", "seconds")
        axes[0].legend(frameon=False, fontsize=8)
        fig.tight_layout(); fig.savefig(CH / "s2-head-of-line.png"); plt.close(fig)

    # ---- S3
    if b.get("S3"):
        md += ["## S3 — oversized uploads (curl, no `Expect: 100-continue`; median of 3)\n",
               "| MB | recipe tryReady | base status | base ms | base bytes sent | after status | after ms | after bytes sent |",
               "|---|---|---|---|---|---|---|---|"]
        amap = {(r["upload_mb"], r["recipe"]): r for r in a.get("S3", [])}
        for r in b["S3"]:
            y = amap.get((r["upload_mb"], r["recipe"]), {})
            md.append(f"| {r['upload_mb']} | {r['tryReady']} | {r['status']} | {r['median_ms']} | {r['bytes_sent_by_client']:,} | "
                      f"{y.get('status','–')} | {y.get('median_ms','–')} | {y.get('bytes_sent_by_client',0):,} |")
        md.append("")
        fig, ax = plt.subplots(figsize=(7, 4), dpi=150)
        for lab, d in (("baseline", b), ("after", a)):
            rs = [r for r in d.get("S3", []) if r["recipe"] == "seed-01"]
            ax.plot([r["upload_mb"] for r in rs], [r["bytes_sent_by_client"] / 2**20 for r in rs], marker="o", ms=5, lw=2, color=C[lab], label=LABEL[lab])
            ax.annotate(f"{rs[-1]['bytes_sent_by_client']/2**20:.1f} MB", (rs[-1]["upload_mb"], rs[-1]["bytes_sent_by_client"] / 2**20),
                        textcoords="offset points", xytext=(-8, 6), ha="right", fontsize=8, color=INK)
        style(ax, "S3 · bytes the client sent before the server rejected it", "upload size (MB)", "MB sent by client (curl size_upload)")
        ax.legend(frameon=False, fontsize=8)
        fig.tight_layout(); fig.savefig(CH / "s3-upload-guard.png"); plt.close(fig)

    for key, title in (("S4", "S4 — hung provider"), ("S5", "S5 — disk written per generate"), ("S6", "S6 — cold start"), ("S7", "S7 — load_recipes() cost")):
        md.append(f"## {title}\n")
        md.append(f"- baseline: `{json.dumps(b.get(key), ensure_ascii=False)}`")
        md.append(f"- after: `{json.dumps(a.get(key), ensure_ascii=False)}`\n")
    (RES / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote", RES / "summary.md", "and charts:", sorted(p.name for p in CH.glob("*.png")))


if __name__ == "__main__":
    main()
